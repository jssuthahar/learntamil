/*
  The one list of stylesheets and scripts.
  tools/build-pages.mjs writes these into index.html (STYLES / SCRIPTS markers), into every
  guide page, and into the service worker's PRECACHE list, so adding a file here is the only
  step needed to ship it (then run `npm run build`).

  ORDER MATTERS. There is no bundler: scripts are plain <script> files that share globals,
  so a file may only use, while it loads, what an earlier file defined (see docs/ARCHITECTURE.md).
  Stylesheets are numbered; later files refine earlier ones.
*/
export const CSS = 'assets/css/';
export const JS = 'assets/js/';

export const STYLES = [
  '00-tokens', '10-base', '20-letters', '21-stories', '22-practice', '30-motion', '40-navigation',
  '41-reading', '42-games', '50-responsive', '60-pages', '70-rewards', '71-certificate',
  '80-premium', '81-chat', '82-today', '83-services', '90-kids'
].map(n => `${CSS}${n}.css`);

/* Data shared with the build tools (they load these in a Node VM). */
/* All content and every child-facing message (see docs/ARCHITECTURE.md → "Where text lives"). */
export const DATA = ['alphabet', 'words', 'stories', 'rhymes', 'festivals', 'rewards', 'pictures', 'messages'].map(n => `${JS}data/${n}.js`);

/* Shared by every page: install app, cookie notice + analytics, support card, Ask Kili chat. */
export const SERVICES = [
  { src: `${JS}services/pwa.js` },
  { src: `${JS}services/firebase.js`, type: 'module' },
  { src: `${JS}services/support.js`, defer: true },
  { src: `${JS}data/faq.js` },          // generated by build-pages
  { src: `${JS}services/chat.js` }
];

/* The learning app (index.html), in load order. */
export const APP_SCRIPTS = [
  `${JS}core/profiles.js`,              // per-child storage keys — first, everything saves through it
  'assets/audio/manifest.js',           // recorded letter sounds (optional)
  ...DATA,
  ...[
    'core/dom', 'core/letter-model', 'core/speech', 'core/sound', 'core/analytics',
    'features/rewards/score', 'features/rewards/progress', 'features/rewards/today', 'features/rewards/path',
    'features/letters/letters',
    'features/stories/story-reader',
    'features/games/game-utils', 'features/games/letter-quiz',
    'features/reading/reading',
    'features/games/hub', 'features/games/spin-wheel', 'features/games/balloon-pop',
    'features/games/word-builder', 'features/games/memory', 'features/games/question-games',
    'features/certificate/certificate',
    'features/games/trace', 'features/games/colouring',
    'features/voice/say-back',
    'features/stories/rhymes',
    'features/little/little',
    'features/family/profile-switcher', 'features/family/stickers', 'features/family/parent-corner', 'features/family/settings',
    'app'                               // router: last, opens the first section
  ].map(n => `${JS}${n}.js`)
].map(src => ({ src }));

/* Pages load ONE stylesheet: the files above joined in order by the build (fewer render-blocking
   requests = faster first paint, which search engines measure). Edit the numbered files, never the bundle. */
export const STYLE_BUNDLE = `${CSS}app.css`;

export const tag = s => `<script${s.type ? ` type="${s.type}"` : ''} src="${s.src}"${s.defer ? ' defer' : ''}></script>`;
export const styleTags = () => `<link rel="stylesheet" href="${STYLE_BUNDLE}">`;
export const scriptTags = list => list.map(tag).join('\n');

/* Everything the offline app needs (service worker PRECACHE), besides the HTML pages. */
export const PRECACHE_ASSETS = [
  STYLE_BUNDLE, ...APP_SCRIPTS.map(s => s.src), ...SERVICES.map(s => s.src).filter(s => !APP_SCRIPTS.some(a => a.src === s)),
  'manifest.webmanifest', 'assets/favicon.svg', 'assets/icon-192.png', 'assets/icon-512.png',
  'assets/icon-maskable-512.png', 'assets/apple-touch-icon.png'
];
